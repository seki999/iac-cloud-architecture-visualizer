export function getAwsResourceRule(resourceType: string, provider = "aws"): AwsResourceRule {
  const rule = provider === "aws" ? AWS_RESOURCE_RULES[resourceType] : undefined;
  if (rule) return rule;

  // Generic fallback for uncataloged AWS resources
  return {
    resourceType,
    category: "other",
    overviewImportance: 3,
    defaultVisible: false,
    visualRole: "node",
    placementStrategy: "global",
    iconKey: "aws.generic",
  };
}
